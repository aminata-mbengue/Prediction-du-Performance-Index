# Importer Gradio et charger les éléments sauvegardés
import streamlit as st
import gradio as gr
import joblib
import numpy as np
import pandas as pd
best_model = joblib.load('best_model.joblib')
scaler = joblib.load('scaler.joblib')


# Fonction de prédiction utilisée par Gradio
def Pred_func(hours_studied, previous_scores, extracurricular_activities,
              sleep_hours, sample_question_papers_practiced):
    # : Yes = 1 et No = 0
    extracurricular = 1 if extracurricular_activities == 'Yes' else 0

    # Construire les variables dans le même ordre que pendant l'entraînement
    x_new = np.array([[
        hours_studied,
        previous_scores,
        extracurricular,
        sleep_hours,
        sample_question_papers_practiced
    ]], dtype=float)

    # Appliquer exactement le même RobustScaler
    x_new = scaler.transform(x_new)

    # Prédiction du Performance Index
    prediction = best_model.predict(x_new)[0]

    return round(float(prediction), 2)


